import { useState } from "react";
import { PlugZap, Eye, EyeOff, Copy, Check, RefreshCw, ShieldCheck, AlertTriangle } from "lucide-react";
import { Button } from "./ui/Button";
import { Badge } from "./ui/Badge";
import { Label, Hint } from "./ui/Form";
import { inputClass } from "../lib/inputStyles";

/**
 * The SIP details a customer hands to their own telephony operator.
 *
 * This exists because Clarivo no longer buys phone numbers on customers' behalf. The
 * customer keeps their number with their operator and forwards it to the trunk we
 * created for them, so these three values — host, username, password — are the entire
 * handover, and the customer has to be able to read them out or paste them into their
 * operator's portal.
 *
 * That is why the password is shown here rather than masked like the WhatsApp token.
 * The WhatsApp token comes FROM the customer, so hiding it costs them nothing; this
 * one is generated by us, so hiding it would leave them unable to complete the setup
 * at all. It is behind a reveal toggle so it is not sitting on screen during a screen
 * share, and `Rotate` is one click away for when it has been shared too widely.
 *
 * No port is quoted anywhere below. A wrong port would send every customer to their
 * operator with bad information, and the `sip:number@host` URI is the form operators
 * actually ask for.
 */

const LIVEKIT_SIP_DOCS = "https://docs.livekit.io/sip/";

/** One read-only value with a copy button. Local to this file — three call sites, all
 *  here, so lifting it into ui/ would spread one card's layout across two files. */
function CopyRow({ label, value, hint, mono = true, secret = false }) {
  const [copied, setCopied] = useState(false);
  const [shown, setShown] = useState(false);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(value || "");
      setCopied(true);
      // Reverts the tick on its own; a copy button that stays ticked reads as if the
      // value is somehow "saved" rather than "copied a moment ago".
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      setCopied(false);
    }
  };

  const masked = secret && !shown;
  return (
    <div>
      <Label>{label}</Label>
      <div className="relative">
        <input
          readOnly
          className={`${inputClass(false)} ${mono ? "font-mono text-[13px]" : ""} pr-20`}
          value={masked ? "•".repeat(Math.min((value || "").length, 32)) : value || ""}
        />
        <div className="absolute right-1.5 top-1/2 flex -translate-y-1/2 items-center gap-0.5">
          {secret && (
            <button
              type="button"
              onClick={() => setShown((s) => !s)}
              className="grid h-8 w-8 place-items-center rounded-lg text-gray-400 hover:bg-gray-100 hover:text-gray-700"
              aria-label={shown ? `Hide ${label}` : `Show ${label}`}
            >
              {shown ? <EyeOff className="h-4 w-4" /> : <Eye className="h-4 w-4" />}
            </button>
          )}
          <button
            type="button"
            onClick={copy}
            className="grid h-8 w-8 place-items-center rounded-lg text-gray-400 hover:bg-gray-100 hover:text-gray-700"
            aria-label={`Copy ${label}`}
          >
            {copied ? <Check className="h-4 w-4 text-emerald-600" /> : <Copy className="h-4 w-4" />}
          </button>
        </div>
      </div>
      {hint && <Hint>{hint}</Hint>}
    </div>
  );
}

export default function SipConnectionCard({
  connection,
  onRotate,
  onSaveAllowed,
  onRetry,
  rotating = false,
  savingAllowed = false,
  retrying = false,
}) {
  const [allowed, setAllowed] = useState(connection?.allowed_addresses || "");
  const [confirmRotate, setConfirmRotate] = useState(false);
  const [advancedOpen, setAdvancedOpen] = useState(false);

  if (!connection?.configured) return null;

  const ready = connection.status === "active";
  const numbers = connection.numbers || [];
  const primary = numbers[0];

  return (
    <div className="rounded-3xl border border-gray-100 bg-white p-6 shadow-sm space-y-5">
      <div className="flex flex-wrap items-start justify-between gap-3 border-b border-gray-100 pb-3">
        <div className="flex items-start gap-2.5">
          <PlugZap className="mt-0.5 h-5 w-5 shrink-0 text-gray-500" />
          <div>
            <h3 className="text-base font-semibold text-gray-950">Your Clarivo connection</h3>
            <p className="mt-0.5 text-sm text-gray-500">
              Give these details to your telephony operator and ask them to send incoming
              calls for your number here.
            </p>
          </div>
        </div>
        <Badge tone={ready ? "success" : "warning"}>{ready ? "Ready" : "Setting up"}</Badge>
      </div>

      {!ready && (
        <div className="rounded-2xl border border-amber-100 bg-amber-50 p-4">
          <div className="flex items-start gap-2 text-sm text-amber-800">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" />
            <span>
              {connection.last_error
                ? connection.last_error
                : numbers.length === 0
                  ? "No active numbers on this connection yet. Your username and password stay the same, so you can set your operator up now and switch a number on when you're ready."
                  : "We're still finishing this connection. Your numbers are saved."}
            </span>
          </div>
          {onRetry && numbers.length > 0 && (
            <div className="mt-3">
              <Button variant="secondary" size="sm" disabled={retrying} onClick={onRetry}>
                <RefreshCw className="h-4 w-4" /> {retrying ? "Retrying..." : "Retry setup"}
              </Button>
            </div>
          )}
        </div>
      )}

      <div className="grid gap-4 sm:grid-cols-2">
        <CopyRow
          label="SIP host"
          value={connection.sip_host}
          hint="Where your operator sends the calls."
        />
        {primary && (
          <CopyRow
            label="SIP URI"
            value={`sip:${primary}@${connection.sip_host}`}
            hint="The full destination, if your operator asks for a URI."
          />
        )}
        <CopyRow label="Username" value={connection.auth_username} />
        <CopyRow label="Password" value={connection.auth_password} secret />
      </div>

      <div>
        <Label>Numbers on this connection</Label>
        <div className="mt-1.5 flex flex-wrap gap-2">
          {numbers.length === 0 ? (
            <span className="text-sm text-gray-400">
              None yet — connect a number and it appears here.
            </span>
          ) : (
            numbers.map((n) => (
              <span
                key={n}
                className="inline-flex items-center rounded-full bg-gray-100 px-2.5 py-1 font-mono text-xs text-gray-700"
              >
                {n}
              </span>
            ))
          )}
        </div>
        <Hint>
          Only numbers you've switched on are accepted here, so a paused number stops
          ringing through immediately.
        </Hint>
      </div>

      <div className="flex items-start gap-2 rounded-2xl border border-blue-100 bg-blue-50 p-4 text-sm text-blue-900">
        <ShieldCheck className="mt-0.5 h-4 w-4 shrink-0" />
        <span>
          After your operator is set up, call your number once. That first call proves
          the number is yours and switches it on — nothing else to do.{" "}
          <a
            className="font-medium underline"
            href={LIVEKIT_SIP_DOCS}
            target="_blank"
            rel="noreferrer"
          >
            Technical reference for your operator
          </a>
          .
        </span>
      </div>

      <div className="border-t border-gray-100 pt-4">
        <button
          type="button"
          onClick={() => setAdvancedOpen((o) => !o)}
          className="text-sm font-medium text-gray-600 hover:text-gray-950"
          aria-expanded={advancedOpen}
        >
          {advancedOpen ? "Hide advanced" : "Advanced"}
        </button>

        {advancedOpen && (
          <div className="mt-4 space-y-5">
            <div>
              <Label htmlFor="sip-allowed">Operator IP addresses (optional)</Label>
              <input
                id="sip-allowed"
                className={`${inputClass(false)} font-mono text-[13px]`}
                value={allowed}
                onChange={(e) => setAllowed(e.target.value)}
                placeholder="203.0.113.5, 198.51.100.0/24"
              />
              <Hint>
                Locks this connection to your operator's addresses, so the password alone
                is not enough to send us calls. Leave empty unless your operator has given
                you these — a wrong value stops every call.
              </Hint>
              <div className="mt-3">
                <Button
                  variant="secondary"
                  size="sm"
                  disabled={savingAllowed}
                  onClick={() => onSaveAllowed(allowed)}
                >
                  {savingAllowed ? "Saving..." : "Save addresses"}
                </Button>
              </div>
            </div>

            <div>
              <Label>Credentials</Label>
              {confirmRotate ? (
                <div className="mt-1.5 rounded-2xl border border-red-100 bg-red-50 p-4">
                  <p className="text-sm text-red-800">
                    New credentials take effect immediately. Calls will fail until you give
                    the new username and password to your operator. Continue?
                  </p>
                  <div className="mt-3 flex gap-2">
                    <Button
                      variant="danger"
                      size="sm"
                      disabled={rotating}
                      onClick={async () => {
                        await onRotate();
                        setConfirmRotate(false);
                      }}
                    >
                      {rotating ? "Rotating..." : "Yes, rotate"}
                    </Button>
                    <Button variant="secondary" size="sm" onClick={() => setConfirmRotate(false)}>
                      Cancel
                    </Button>
                  </div>
                </div>
              ) : (
                <>
                  <div className="mt-1.5">
                    <Button variant="secondary" size="sm" onClick={() => setConfirmRotate(true)}>
                      <RefreshCw className="h-4 w-4" /> Rotate credentials
                    </Button>
                  </div>
                  <Hint>Use this if the password has been shared outside your team.</Hint>
                </>
              )}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
